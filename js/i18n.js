/* ─── CURRENCY ───
   Fixed approximate rates — not live, not a binding quote.
   Final price is always confirmed in USD at booking. */
const CURRENCY = {
  en: { code: 'USD', symbol: '$',   rate: 1,    prefix: true  },
  fr: { code: 'EUR', symbol: '€',   rate: 0.92, prefix: false },
  es: { code: 'EUR', symbol: '€',   rate: 0.92, prefix: false },
  ar: { code: 'MAD', symbol: 'MAD', rate: 10,   prefix: false },
  it: { code: 'EUR', symbol: '€',   rate: 0.92, prefix: false },
};

function formatPrice(usd, lang) {
  const c = CURRENCY[lang] || CURRENCY.en;
  const converted = Math.round(usd * c.rate).toLocaleString('en-US');
  return c.prefix ? `${c.symbol}${converted}` : `${converted} ${c.symbol}`;
}

function applyCurrency(lang) {
  document.querySelectorAll('[data-price-usd]').forEach(el => {
    const usd = parseFloat(el.dataset.priceUsd);
    if (!isNaN(usd)) el.textContent = formatPrice(usd, lang);
  });
}

/* ─── APPLY TRANSLATIONS ───
   Merges the shared site-wide TRANSLATIONS with an optional page-local
   PAGE_TRANSLATIONS object (defined inline on individual tour pages),
   so each page can carry its own large translation payload without
   bloating this shared file. Page-local keys win on collision. */
function applyLang(lang) {
  const shared = TRANSLATIONS[lang] || {};
  const page   = (typeof PAGE_TRANSLATIONS !== 'undefined' && PAGE_TRANSLATIONS[lang]) || {};
  const t = Object.assign({}, shared, page);
  if (!Object.keys(t).length) return;

  applyCurrency(lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.dataset.i18n;
    if (t[k] !== undefined) el.textContent = t[k];
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const k = el.dataset.i18nHtml;
    if (t[k] !== undefined) el.innerHTML = t[k];
  });

  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const k = el.dataset.i18nPh;
    if (t[k] !== undefined) el.placeholder = t[k];
  });

  /* Select options */
  document.querySelectorAll('[data-i18n-opt]').forEach(el => {
    const k = el.dataset.i18nOpt;
    if (t[k] !== undefined) el.textContent = t[k];
  });

  /* RTL for Arabic */
  const html = document.documentElement;
  html.lang = lang;
  html.dir  = lang === 'ar' ? 'rtl' : 'ltr';

  /* Active button state */
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
    b.setAttribute('aria-pressed', b.dataset.lang === lang ? 'true' : 'false');
  });

  localStorage.setItem('st_lang', lang);
}

/* ─── INIT ─── */
document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('st_lang') || 'en';
  applyLang(saved);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });
});
